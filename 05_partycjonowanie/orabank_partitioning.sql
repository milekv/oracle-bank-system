-- Opcjonalny wariant tabel do laboratorium Oracle Partitioning.
-- Nie uruchamiaj razem z instalacją podstawową bez planu migracji danych.

CREATE TABLE BANK_TRANSACTION_PART (
    TRANSACTION_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ACCOUNT_ID       NUMBER NOT NULL,
    TRANSACTION_DATE DATE DEFAULT SYSDATE NOT NULL,
    AMOUNT           NUMBER(15,2) NOT NULL,
    TRANSACTION_TYPE VARCHAR2(30) NOT NULL,
    DESCRIPTION      VARCHAR2(200),
    BALANCE_AFTER    NUMBER(15,2),
    CONSTRAINT PK_BANK_TX_PART PRIMARY KEY (TRANSACTION_ID, TRANSACTION_DATE),
    CONSTRAINT FK_BANK_TX_PART_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNT(ACCOUNT_ID)
)
PARTITION BY RANGE (TRANSACTION_DATE)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH')) (
    PARTITION BANK_TX_BEFORE_2026 VALUES LESS THAN (DATE '2026-01-01')
);

CREATE TABLE BALANCE_HISTORY_PART (
    HISTORY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ACCOUNT_ID NUMBER NOT NULL,
    BALANCE    NUMBER(15,2) NOT NULL,
    CHANGE_DATE DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_BALANCE_HISTORY_PART PRIMARY KEY (HISTORY_ID, CHANGE_DATE),
    CONSTRAINT FK_BALANCE_PART_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNT(ACCOUNT_ID)
)
PARTITION BY RANGE (CHANGE_DATE)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH')) (
    PARTITION BALANCE_BEFORE_2026 VALUES LESS THAN (DATE '2026-01-01')
);
